a = int(input("Enter first number: "))
b = int(input("Enter second number: "))
# Addition
c = a + b
print("The sum of", a, "and", b, "is:", c)
# Subtraction
d = a - b
print("The difference of", a, "and", b, "is:", d)
# Multiplication
e = a * b
print("The product of", a, "and", b, "is:", e)
# Division
f = a / b
print("The quotient of", a, "and", b, "is:", f)